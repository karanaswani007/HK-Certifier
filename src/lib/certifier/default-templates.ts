import type { CertElement, CertLayout } from "./types";

const W = 1123;
const H = 794;

function el(partial: Partial<CertElement> & Pick<CertElement, "id" | "type" | "x" | "y" | "w" | "h">): CertElement {
  return {
    rotation: 0,
    zIndex: 1,
    locked: false,
    opacity: 1,
    ...partial,
  };
}

function classicFrame(id: string, stroke: string, inset = 28, width = 3): CertElement[] {
  return [
    el({
      id: `${id}-outer`,
      type: "rect",
      x: inset,
      y: inset,
      w: W - inset * 2,
      h: H - inset * 2,
      fill: "transparent",
      stroke,
      strokeWidth: width,
      zIndex: 2,
    }),
    el({
      id: `${id}-inner`,
      type: "rect",
      x: inset + 10,
      y: inset + 10,
      w: W - (inset + 10) * 2,
      h: H - (inset + 10) * 2,
      fill: "transparent",
      stroke,
      strokeWidth: 1,
      zIndex: 2,
    }),
  ];
}

